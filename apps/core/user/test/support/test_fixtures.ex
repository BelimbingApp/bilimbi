defmodule Bilimbi.Core.User.TestFixtures do
  @moduledoc """
  Lightweight User fixtures for public-API tests.

  These temporary tables exercise query behavior. Exact PostgreSQL
  compatibility is covered independently by the schema contract.

  Company and Employee table DDL is not restated here: it is defined once by
  the module that owns it and reused through that module's fixtures.
  """

  alias Bilimbi.Base.Database.TestTables
  alias Bilimbi.Base.Repo
  alias Bilimbi.Core.Employee.TestFixtures, as: EmployeeFixtures
  alias Bilimbi.Core.User.Password
  alias Ecto.Adapters.SQL

  def password_hash(password \\ "password"), do: Password.hash(password)

  def legacy_password_hash(password \\ "password") do
    password
    |> Bcrypt.hash_pwd_salt(log_rounds: 4)
    |> String.replace_prefix("$2b$", "$2y$")
  end

  # Generated by PHP's PASSWORD_ARGON2ID with Belimbing's canonical
  # memory=19456 KiB, time=2, threads=1 configuration.
  def laravel_argon2_password_hash do
    "$argon2id$v=19$m=19456,t=2,p=1$" <>
      "OTk4dW1zRzBTUFkyQlE5ZA$5feI+G5D3AYm7qIywmS4kZKR4T8gyfzWTIG5JWALvtk"
  end

  alias Bilimbi.Base.Authz.ContributionValidator
  alias Bilimbi.Base.ModuleRegistry.ContributionRegistry

  def create_user_tables! do
    apply(EmployeeFixtures, :create_employee_tables!, [])
    apply(Bilimbi.Core.Company.TestFixtures, :create_external_access_tables!, [])

    create_users_table!()

    SQL.query!(
      Repo,
      """
      CREATE TEMPORARY TABLE password_reset_tokens (
        email varchar(255) PRIMARY KEY,
        token varchar(255) NOT NULL,
        created_at timestamp(0) without time zone
      ) ON COMMIT PRESERVE ROWS
      """,
      []
    )

    create_notifications_table!()
  end

  def create_users_table!(opts \\ []) do
    persistent = TestTables.persistent?(opts)

    SQL.query!(
      Repo,
      """
      #{TestTables.create(persistent)} users (
        id bigserial PRIMARY KEY,
        company_id bigint,
        employee_id bigint,
        name varchar(255) NOT NULL,
        email varchar(255) NOT NULL,
        email_verified_at timestamp(0) without time zone,
        password varchar(255) NOT NULL,
        remember_token varchar(100),
        created_at timestamp(0) without time zone,
        updated_at timestamp(0) without time zone
      ) #{TestTables.on_commit(persistent)}
      """,
      []
    )

    # Named explicitly, not an inline UNIQUE. PostgreSQL would name that
    # `users_email_key`, but the migration creates `users_email_unique` and the
    # changeset maps that name to a field error. A fixture that invents its own
    # constraint name turns a caught error into a raised ConstraintError.
    SQL.query!(Repo, "CREATE UNIQUE INDEX users_email_unique ON users (email)", [])
  end

  def create_bootstrap_receipt_table!(opts \\ []) do
    persistent = TestTables.persistent?(opts)

    SQL.query!(
      Repo,
      """
      #{TestTables.create(persistent)} bilimbi_user_bootstrap (
        id bigint PRIMARY KEY,
        tenant_name varchar(255) NOT NULL,
        company_name varchar(255) NOT NULL,
        company_code varchar(255) NOT NULL,
        admin_email varchar(255) NOT NULL,
        user_id bigint NOT NULL,
        company_id bigint NOT NULL,
        tenant_id bigint NOT NULL,
        completed_at timestamp(0) without time zone NOT NULL,
        CONSTRAINT bilimbi_user_bootstrap_singleton CHECK (id = 1)
      ) #{TestTables.on_commit(persistent)}
      """,
      []
    )
  end

  def create_user_database_queries_table! do
    SQL.query!(
      Repo,
      """
      CREATE TEMPORARY TABLE user_database_queries (
        id bigserial PRIMARY KEY,
        user_id bigint NOT NULL,
        name varchar(150) NOT NULL,
        slug varchar(200) NOT NULL,
        prompt text,
        sql_query text NOT NULL,
        description text,
        icon varchar(100),
        created_at timestamp(0) without time zone,
        updated_at timestamp(0) without time zone
