      []
    )

    SQL.query!(
      Repo,
      "CREATE UNIQUE INDEX user_database_queries_user_id_slug_unique ON user_database_queries (user_id, slug)",
      []
    )

    SQL.query!(
      Repo,
      "CREATE INDEX user_database_queries_user_id_index ON user_database_queries (user_id)",
      []
    )
  end

  def install_user_authz_registry! do
    ContributionRegistry.put_consumers_for_test!(
      %{settings: [], authz: user_authz_snapshot(), menu: []},
      "user-test"
    )
  end

  @doc """
  The validated Authz snapshot of Base Authz, Core Company's directory and
  Core User's own capabilities. A test that signs a user in and reads a
  company through `Bilimbi.Core.Company` needs it installed: Company's
  summary withholds its sensitive fields through the reader's effective
  capabilities, which the company directory resolves.
  """
  def user_authz_snapshot do
    ContributionValidator.validate_contributions!([
      %{
        descriptor: %{
          id: "base/authz",
          otp_app: :bilimbi_base_authz
        },
        payload: Bilimbi.Base.Authz.Contributions.contributions()[:authz]
      },
      %{
        descriptor: %{
          id: "core/company",
          otp_app: :bilimbi_core_company
        },
        payload: %{
          domains: %{"core" => "Core platform modules"},
          capabilities: [
            "admin.company.view",
            "admin.company.list",
            "admin.company.manage"
          ],
          roles: %{},
          company_directory: Bilimbi.Core.Company.AuthzCompanyDirectory
        }
      },
      %{
        descriptor: %{
          id: "core/user",
          otp_app: :bilimbi_core_user
        },
        payload: Bilimbi.Core.User.Contributions.contributions()[:authz]
      }
    ])
  end

  def insert_user!(attributes \\ %{}) do
    attributes =
      Map.merge(
        %{
          id: 91,
          company_id: 73,
          employee_id: nil,
          name: "Ada Lovelace",
          email: "ada@example.com",
          email_verified_at: nil,
          password_hash: password_hash(),
          remember_token: nil
        },
        attributes
      )

    SQL.query!(
      Repo,
      """
      INSERT INTO users (
        id, company_id, employee_id, name, email, email_verified_at, password, remember_token
      )
      VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
      """,
      [
        attributes.id,
        attributes.company_id,
        attributes.employee_id,
        attributes.name,
        attributes.email,
        attributes.email_verified_at,
        attributes.password_hash,
        attributes.remember_token
      ]
    )
  end

  def stored_password(user_id) do
    %{rows: [[password]]} =
      SQL.query!(Repo, "SELECT password FROM users WHERE id = $1", [user_id])

    password
  end

  def stored_remember_token(user_id) do
    %{rows: [[remember_token]]} =
      SQL.query!(Repo, "SELECT remember_token FROM users WHERE id = $1", [user_id])

    remember_token
  end

  def stored_reset_token(email) do
    %{rows: [[token]]} =
      SQL.query!(Repo, "SELECT token FROM password_reset_tokens WHERE email = $1", [email])

    token
  end

  def expire_reset_token!(email) do
    SQL.query!(
      Repo,
      "UPDATE password_reset_tokens SET created_at = $1 WHERE email = $2",
      [~N[2000-01-01 00:00:00], email]
    )
  end

  def create_user_pins_table! do
    SQL.query!(
      Repo,
      """
      CREATE TEMPORARY TABLE IF NOT EXISTS user_pins (
        id bigserial PRIMARY KEY,
        user_id bigint NOT NULL,
        label varchar(150) NOT NULL,
        url varchar(500) NOT NULL,
        url_hash char(32) NOT NULL,
        icon varchar(100),
        sort_order smallint NOT NULL DEFAULT 0,
        created_at timestamp(0) without time zone,
        updated_at timestamp(0) without time zone
      ) ON COMMIT PRESERVE ROWS
      """,
      []
    )

    SQL.query!(
      Repo,
      "CREATE UNIQUE INDEX IF NOT EXISTS user_pins_user_id_url_hash_unique ON user_pins (user_id, url_hash)",
      []
    )

    SQL.query!(
      Repo,
      "CREATE INDEX IF NOT EXISTS user_pins_user_id_sort_order_index ON user_pins (user_id, sort_order)",
      []
    )
  end

  def create_notifications_table! do
    SQL.query!(
      Repo,
      """
      CREATE TEMPORARY TABLE IF NOT EXISTS notifications (
        id uuid PRIMARY KEY,
        type varchar(255) NOT NULL,
        notifiable_type varchar(255) NOT NULL,
        notifiable_id bigint NOT NULL,
        data text NOT NULL,
        read_at timestamp(0) without time zone,
        created_at timestamp(0) without time zone,
        updated_at timestamp(0) without time zone
      ) ON COMMIT PRESERVE ROWS
      """,
      []
    )

    SQL.query!(
      Repo,
      "CREATE INDEX IF NOT EXISTS notifications_notifiable_type_notifiable_id_index ON notifications (notifiable_type, notifiable_id)",
      []
    )
  end
end
